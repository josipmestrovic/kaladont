<h1>O igri</h1>

<p>
  <strong>Kaladont</strong> je nekad bila poznata hrvatska pasta za zube — a i riječ „kaladont" ima posebno
  svojstvo: završava na „nt", a nijedna hrvatska riječ ne počinje tim slovima. Otud i igra: reci riječ koja
  postavlja protivnika u nerješiv položaj.
</p>

