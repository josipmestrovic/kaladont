  <section>
    <h2>2. Dobno ograničenje: 16+</h2>
    <p>
      Kaladont je namijenjen osobama koje imaju <strong>najmanje 16 godina</strong>. Osobe mlađe od 16
      godina ne smiju koristiti igru, ni kao gosti ni putem registriranog korisničkog računa. Dobno
      ograničenje vrijedi za javne partije, privatne sobe i način Zagrijavanje. Informativne stranice,
      poput pravila igre i ovih Uvjeta, mogu se čitati bez igranja.
    </p>
    <p>
      Pri otvaranju računa tražimo da potvrdiš da imaš najmanje 16 godina te da prihvaćaš ove Uvjete
      korištenja. <strong>Ta izjava nije neovisna provjera stvarne dobi.</strong> Ako saznamo da
      korisnik ne ispunjava dobni uvjet, možemo mu onemogućiti korištenje igre ili zatvoriti račun uz
      postupanje s podacima prema
      <a href="/privatnost">Pravilima privatnosti</a> i primjenjivim propisima.
    </p>
    <p>
      Ne objavljuj puno ime i prezime, adresu, naziv škole, telefonski broj, email adresu ili druge
      osobne podatke u nadimku i drugim javnim dijelovima igre. Za pitanja o dobnom ograničenju možeš
      nam pisati na <a href="mailto:info@kaladont.hr">info@kaladont.hr</a>.
    </p>
  </section>

  <section>
    <h2>3. Gosti i korisnički računi</h2>
    <p>
      Kaladont možeš igrati kao gost bez otvaranja računa. Registrirani račun omogućuje čuvanje
      napretka i pristup dodatnim značajkama, kao što su statistika, dostignuća i misije.
    </p>
    <p>
      Za otvaranje računa potreban je nadimak, email adresa i lozinka te potvrda da imaš najmanje 16
      godina i da prihvaćaš Uvjete korištenja. Odaberi nadimak koji ne otkriva tuđe ili tvoje osjetljive
      podatke i nemoj dijeliti lozinku ili pristup računu. Nije dopušteno otvaranje ili korištenje
      računa radi zaobilaženja zabrane pristupa ili namještanja rezultata.
    </p>
    <p>
      Ako želiš zatražiti pristup, ispravak ili brisanje podataka računa, piši s registrirane email
      adrese na <a href="mailto:info@kaladont.hr">info@kaladont.hr</a>. Pri brisanju računa podaci se
      uklanjaju ili anonimiziraju prema <a href="/privatnost">Pravilima privatnosti</a>; zajednička
      povijest partija može ostati u anonimiziranom obliku radi očuvanja rezultata drugih sudionika.
    </p>
  </section>

  <section>
    <h2>4. Pravila igre i rječnik</h2>
    <p>
      Kaladont se igra prema pravilima pojedinog načina igre, objavljenima na stranici
      <a href="/pravila-kaladonta">Pravila igre</a>. Rječnik i provjera riječi automatizirani su, pa se
      mogu dogoditi pogreške, primjerice neprihvaćanje valjane riječi ili prihvaćanje sporne riječi.
    </p>
    <p>
      Odluke igre o valjanosti poteza i završetku partije nastaju prema pravilima i stanju sustava u
      trenutku odigravanja. Ako smatraš da je riječ pogrešno ocijenjena, možeš je prijaviti kroz igru.
      Pregledom prijava možemo ispraviti rječnik i buduće odluke; ne obećavamo automatsko retroaktivno
      mijenjanje svih prethodnih rezultata.
    </p>
  </section>

  <section>
    <h2>5. Računalni protivnici (botovi)</h2>
    <p>
      U javnim partijama Kaladonta mogu sudjelovati <strong>botovi</strong>, odnosno računalni
      protivnici kojima upravlja igra. Ako u čekaonici nema dovoljno stvarnih igrača, sustav može
      popuniti slobodna mjesta botovima. Uobičajeno se to događa nakon približno 30 sekundi u Dvoboju
      te postupno nakon otprilike 20, 30 i 40 sekundi u Četveroboju. Vremena su okvirna i mogu se
      mijenjati.
    </p>
    <p>
      Botovi koriste rječnik igre i podliježu istim osnovnim pravilima poteza, vremena, provjere riječi
      i ispadanja kao ljudski igrači. U pravilu češće biraju poznatije riječi i odgovaraju različitim
      brzinama. Ponekad mogu odustati, zakasniti, pogriješiti ili propustiti priliku za riječ
      „kaladont”. Mogu slati i unaprijed definirane kratke reakcije. Botovi ne pokušavaju sustavno
      tražiti riječi kojima bi protivnika ostavili bez nastavka. Njihovo se ponašanje može prilagođavati
      tijekom razvoja igre.
    </p>
    <p>
      <strong>Botovi su računalni protivnici, a ne stvarni korisnici.</strong> Imaju prepoznatljive
      ilustrirane avatare namijenjene botovima. Više botova može dijeliti istu ilustraciju avatara, ali
      zadržava vlastiti nadimak. Na završnom poretku bot se označava tekstom „Bot”; njegov nadimak nije
      poveznica na javni profil. Botovi nemaju javne korisničke profile, ne sudjeluju na ljudskim
      ljestvicama niti dobivaju korisničke rangove, XP, dostignuća i ostali osobni napredak.
    </p>
    <p>
      <strong>Ljudima se javna partija s botovima računa kao i druga javna partija.</strong> Ako igraš
      protiv jednog ili više botova, tvoji bodovi, XP, dostignuća i položaj na ljestvicama mogu se
      mijenjati prema redovnim pravilima igre. Botovi sami nisu kandidati za ljudski poredak. Sustav
      može čuvati nužne tehničke zapise njihovih poteza i rezultata kako bi igra ispravno funkcionirala.
    </p>
    <p>
      U načinu <strong>Zagrijavanje</strong> igraš protiv računala bez vremenskog ograničenja. Taj način
      ne donosi natjecateljske bodove, XP ili rang, ali registriranim igračima može donositi napredak
      dostignuća namijenjenih zagrijavanju.
    </p>
  </section>

  <section>
    <h2>6. Poštena igra i primjereno ponašanje</h2>
    <p>
      Želimo da Kaladont bude ugodno i pošteno mjesto za sve. Nisu dopušteni uvredljivi, prijeteći,
      diskriminatorni, seksualno eksplicitni ili obmanjujući nadimci, lažno predstavljanje kao druga
      osoba te uznemiravanje drugih igrača.
    </p>
    <p>
      Nije dopušteno namještanje partija i rezultata, neovlašteno automatiziranje igranja,
      iskorištavanje sigurnosnih propusta, ometanje rada sustava, zaobilaženje ograničenja ili slanje
      lažnih prijava radi uznemiravanja. Pomagala za pristupačnost, poput čitača zaslona i prilagođenih
      fontova, nisu zabranjena.
    </p>
    <p>
      Ako primijetiš sigurnosni propust, prijavi ga na
      <a href="mailto:info@kaladont.hr">info@kaladont.hr</a>, bez iskorištavanja propusta ili
      pristupanja tuđim podacima.
    </p>
  </section>

  <section>
    <h2>7. Prijave i moderacija</h2>
    <p>
      Neprimjeren nadimak možeš prijaviti putem opcije <strong>Prijavi igrača</strong>. Netočne ili
      sporne riječi možeš prijaviti putem opcije <strong>Prijavi riječ</strong>. Za druge poteškoće ili
      prigovore možeš nam pisati na <a href="mailto:info@kaladont.hr">info@kaladont.hr</a>.
    </p>
    <p>
      Prijave provjeravamo prema dostupnim podacima. To se odnosi i na saznanja da račun koristi osoba
      mlađa od 16 godina. Ovisno o ozbiljnosti i ponavljanju kršenja pravila, možemo zatražiti promjenu
      nadimka, upozoriti korisnika ili, kada je to opravdano i tehnički omogućeno, privremeno ograničiti
      ili trajno onemogućiti pristup računu. O mjerama ćemo informirati korisnika kada je primjereno i
      kada to ne ugrožava sigurnost ili prava drugih osoba. Prigovor na odluku može se poslati na isti
      kontakt.
    </p>
    <p>Ova pravila ne umanjuju prava korisnika koja proizlaze iz primjenjivih propisa.</p>
  </section>

  <section>
    <h2>8. Bodovi, rangovi i digitalne nagrade</h2>
    <p>
      Kaladont uključuje bodove, iskustvo (XP), razine, rangove, ljestvice, misije, dostignuća,
      kolekciju riječi i druge značajke napredovanja. To su <strong>isključivo elementi igre</strong>:
      nemaju stvarnu novčanu vrijednost, ne mogu se zamijeniti za novac i ne predstavljaju novčanu
      nagradu.
    </p>
    <p>
      Pravila obračuna, uvjeti za nagrade i način prikaza ljestvica mogu se mijenjati radi ispravljanja
      grešaka, poštenog natjecanja ili poboljšanja igre. Ako je potrebna značajna izmjena koja utječe
      na postojeći napredak, nastojat ćemo je jasno najaviti i izbjeći nepotreban gubitak podataka. Ne
      jamčimo da će svi elementi napredovanja zauvijek ostati nepromijenjeni.
    </p>
  </section>

  <section>
    <h2>9. Dostupnost, razvoj igre i odgovornost</h2>
    <p>
      Kaladont se aktivno razvija. Povremeno može biti nedostupan zbog održavanja, tehničkih poteškoća,
      promjena rječnika ili sigurnosnih razloga. Pojedina partija može se prekinuti ili završiti bez
      očekivanog rezultata ako dođe do tehničke pogreške.
    </p>
    <p>
      Nastojimo održavati igru pouzdanom i ispravljati prijavljene probleme, ali ne možemo jamčiti
      neprekidnu dostupnost ili potpuno odsustvo pogrešaka. Ništa u ovim Uvjetima ne ograničava
      odgovornost ili prava korisnika koja nije dopušteno ograničiti zakonom.
    </p>
  </section>

