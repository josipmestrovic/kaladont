/**
 * Lokalni dekorativni fond za pozadinske partije na naslovnici.
 *
 * Samo uobičajene, frekventne hrvatske riječi. Nisu potvrđene produkcijskom bazom.
 * Grupe: `oblika:<rijec>`.
 */

export interface PozadinskaRijec {
  rijec: string;
  grupe: readonly string[];
}

function unos(rijec: string): PozadinskaRijec {
  const normalizirana = rijec.normalize('NFC').toLowerCase();
  return { rijec: normalizirana, grupe: [`oblika:${normalizirana}`] };
}

