function izgradiFond(sirove: readonly string[]): readonly PozadinskaRijec[] {
  const vidjene = new Set<string>();
  const rezultat: PozadinskaRijec[] = [];
  for (const sirova of sirove) {
    const stavka = unos(sirova);
    if (vidjene.has(stavka.rijec)) continue;
    if (stavka.rijec === POSEDNA_RIJEC_KALADONT) continue;
    if (stavka.rijec.length < 2) continue;
    vidjene.add(stavka.rijec);
    rezultat.push(stavka);
  }
  return rezultat;
}

